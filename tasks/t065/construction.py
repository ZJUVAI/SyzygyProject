"""Conversions for the historical Moser-lattice witness and grid search."""

from fractions import Fraction

from tasks.t065.check import PARAMETERS


FIELD = {
    "minimal_polynomial": [64, 0, -28, 0, 1],
    "isolating_interval": ["5", "51/10"],
}


def _rational_text(value):
    value = Fraction(value)
    return str(value.numerator) if value.denominator == 1 else f"{value.numerator}/{value.denominator}"


def point_from_moser_tuple(row):
    """Encode a+b*w1+c*w3+d*w1*w3 in Q(alpha), alpha=sqrt(3)+sqrt(11)."""
    a, b, c, d = row
    x = [
        Fraction(a) + Fraction(b, 2) + Fraction(5 * c, 6) + d,
        Fraction(0),
        Fraction(-d, 24),
        Fraction(0),
    ]
    y = [
        Fraction(0),
        Fraction(-5 * b, 8) + Fraction(3 * c, 8) - Fraction(d, 3),
        Fraction(0),
        Fraction(b, 32) - Fraction(c, 96) + Fraction(d, 48),
    ]
    return {"x": [_rational_text(v) for v in x],
            "y": [_rational_text(v) for v in y]}


def solution_from_moser_tuples(rows, provenance):
    if len(rows) != 100:
        raise ValueError("exactly 100 Moser-lattice points are required")
    return {
        **FIELD,
        "points": [point_from_moser_tuple(row) for row in rows],
        "construction_provenance": provenance,
    }


def grid_tuples(columns, rows):
    return [(column, row, 0, 0)
            for row in range(rows)
            for column in range(columns)]


def grid_edge_count(columns, rows):
    """Count the three positive unit directions in a triangular lattice patch."""
    return (columns - 1) * rows + columns * (rows - 1) + (columns - 1) * (rows - 1)


def rectangular_grid(columns, rows):
    return solution_from_moser_tuples(
        grid_tuples(columns, rows),
        f"{columns}-by-{rows} patch of the triangular lattice generated by 1 and w1",
    )
